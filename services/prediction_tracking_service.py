"""
Service for tracking predictions and computing accuracy metrics.

This service:
- Stores predictions when generated by the API
- Compares predictions with actual results after matches finish
- Computes accuracy for each betting market
- Calculates calibration metrics
- Computes rolling accuracy over time windows
"""

from datetime import datetime, timedelta, timezone
from typing import Dict, Any, List, Optional, Tuple
import numpy as np
from sqlalchemy.orm import Session
from sqlalchemy import func, and_, or_

from models import (
    Match,
    BettingMarketPrediction,
    PredictionAccuracy,
    CalibrationMetrics,
    RollingAccuracy,
)
from utils.logger import logger


class PredictionTrackingService:
    """Service for tracking predictions and computing analytics."""

    MARKET_TYPES = [
        "match_winner",  # 1X2
        "asian_handicap",
        "asian_total",
        "btts",
        "clean_sheet",
        "correct_score",
    ]

    def store_betting_market_prediction(
        self,
        db: Session,
        match_id: int,
        market_type: str,
        predicted_value: Optional[str],
        predicted_probability: Optional[float],
        model_version: str,
        source: str,
        prediction_data: Optional[Dict[str, Any]] = None,
    ) -> BettingMarketPrediction:
        """
        Store a betting market prediction.

        Args:
            db: Database session
            match_id: Match ID
            market_type: Type of betting market
            predicted_value: Predicted discrete value (e.g., "1-0" for correct score)
            predicted_probability: Predicted probability (for binary markets)
            model_version: Model version used
            source: Source of prediction (ml_model or poisson_fallback)
            prediction_data: Additional prediction data as JSON

        Returns:
            Created BettingMarketPrediction record
        """
        prediction = BettingMarketPrediction(
            match_id=match_id,
            market_type=market_type,
            predicted_value=predicted_value,
            predicted_probability=predicted_probability,
            model_version=model_version,
            source=source,
            prediction_data=prediction_data,
        )
        db.add(prediction)
        db.commit()
        db.refresh(prediction)
        logger.info(f"Stored {market_type} prediction for match {match_id}")
        return prediction

    def evaluate_finished_matches(
        self, db: Session, since: Optional[datetime] = None
    ) -> int:
        """
        Evaluate predictions for recently finished matches.

        Args:
            db: Database session
            since: Only evaluate matches finished after this time

        Returns:
            Number of matches evaluated
        """
        if since is None:
            since = datetime.now(timezone.utc) - timedelta(days=7)

        # Find finished matches that haven't been evaluated yet
        evaluated_match_ids = db.query(PredictionAccuracy.match_id).distinct().all()
        evaluated_ids = [mid[0] for mid in evaluated_match_ids]

        matches = (
            db.query(Match)
            .filter(
                Match.status == "FINISHED",
                Match.home_score.isnot(None),
                Match.away_score.isnot(None),
                Match.utc_date >= since,
            )
            .filter(~Match.id.in_(evaluated_ids) if evaluated_ids else True)
            .all()
        )

        evaluated_count = 0
        for match in matches:
            try:
                self._evaluate_match_predictions(db, match)
                evaluated_count += 1
            except Exception as e:
                logger.error(f"Failed to evaluate match {match.id}: {e}", exc_info=True)

        logger.info(f"Evaluated {evaluated_count} finished matches")
        return evaluated_count

    def _evaluate_match_predictions(self, db: Session, match: Match) -> None:
        """Evaluate all predictions for a single finished match."""
        home_score = match.home_score or 0
        away_score = match.away_score or 0
        goal_diff = home_score - away_score
        total_goals = home_score + away_score

        # Get predictions for this match
        predictions = (
            db.query(BettingMarketPrediction)
            .filter(BettingMarketPrediction.match_id == match.id)
            .all()
        )

        for pred in predictions:
            accuracy = self._compute_prediction_accuracy(
                pred, home_score, away_score, goal_diff, total_goals
            )
            if accuracy:
                db.add(accuracy)

        db.commit()

    def _compute_prediction_accuracy(
        self,
        prediction: BettingMarketPrediction,
        home_score: int,
        away_score: int,
        goal_diff: int,
        total_goals: int,
    ) -> Optional[PredictionAccuracy]:
        """Compute accuracy for a single prediction."""
        market_type = prediction.market_type
        predicted_value = prediction.predicted_value
        predicted_prob = prediction.predicted_probability

        actual_value = None
        is_correct = False
        confidence = predicted_prob

        if market_type == "match_winner":
            # 1X2 prediction
            if goal_diff > 0:
                actual_value = "HOME_WIN"
            elif goal_diff < 0:
                actual_value = "AWAY_WIN"
            else:
                actual_value = "DRAW"
            is_correct = predicted_value == actual_value
            confidence = prediction.prediction_data.get("confidence") if prediction.prediction_data else None

        elif market_type == "asian_handicap":
            # Home -0.5: 1 if home wins, 0 otherwise
            actual_value = "1" if goal_diff > 0 else "0"
            predicted_val = "1" if predicted_value and predicted_value.startswith("Home") else "0"
            is_correct = predicted_val == actual_value
            confidence = prediction.predicted_probability

        elif market_type == "asian_total":
            # Over/Under 2.5: 1 if over, 0 otherwise
            actual_value = "1" if total_goals > 2.5 else "0"
            predicted_val = "1" if predicted_value and predicted_value.startswith("Over") else "0"
            is_correct = predicted_val == actual_value
            confidence = prediction.predicted_probability

        elif market_type == "btts":
            # Both teams to score: 1 if both score, 0 otherwise
            actual_value = "1" if (home_score > 0 and away_score > 0) else "0"
            predicted_val = "1" if predicted_value and predicted_value == "Yes" else "0"
            is_correct = predicted_val == actual_value
            confidence = prediction.predicted_probability

        elif market_type == "clean_sheet":
            # Home clean sheet: 1 if away scores 0, 0 otherwise
            actual_value = "1" if away_score == 0 else "0"
            predicted_val = "1" if predicted_value and predicted_value == "Yes" else "0"
            is_correct = predicted_val == actual_value
            confidence = prediction.predicted_probability

        elif market_type == "correct_score":
            # Exact score
            actual_value = f"{home_score}-{away_score}"
            is_correct = predicted_value == actual_value
            confidence = prediction.prediction_data.get("probability") if prediction.prediction_data else None

        else:
            logger.warning(f"Unknown market type: {market_type}")
            return None

        return PredictionAccuracy(
            match_id=prediction.match_id,
            market_type=market_type,
            predicted_value=predicted_value,
            actual_value=actual_value,
            predicted_probability=predicted_prob,
            is_correct=is_correct,
            confidence=confidence,
            model_version=prediction.model_version,
            source=prediction.source,
            match_date=prediction.match.utc_date if prediction.match else datetime.now(timezone.utc),
        )

    def compute_calibration_metrics(
        self, db: Session, market_type: str, bucket_size: int = 10
    ) -> List[CalibrationMetrics]:
        """
        Compute calibration metrics for a market.

        Args:
            db: Database session
            market_type: Market type to compute calibration for
            bucket_size: Number of confidence buckets

        Returns:
            List of CalibrationMetrics records
        """
        # Get all accuracy records for this market with confidence
        records = (
            db.query(PredictionAccuracy)
            .filter(
                PredictionAccuracy.market_type == market_type,
                PredictionAccuracy.confidence.isnot(None),
            )
            .all()
        )

        if not records:
            logger.warning(f"No records found for calibration: {market_type}")
            return []

        # Create confidence buckets
        confidences = np.array([r.confidence for r in records])
        correct = np.array([1 if r.is_correct else 0 for r in records])

        bucket_edges = np.linspace(0, 1, bucket_size + 1)
        calibration_records = []

        for i in range(bucket_size):
            min_conf = bucket_edges[i]
            max_conf = bucket_edges[i + 1]
            
            # Find records in this bucket
            mask = (confidences >= min_conf) & (confidences < max_conf)
            if i == bucket_size - 1:  # Include max in last bucket
                mask = (confidences >= min_conf) & (confidences <= max_conf)
            
            if mask.sum() == 0:
                continue
            
            bucket_correct = correct[mask]
            bucket_conf = confidences[mask]
            
            total = len(bucket_correct)
            correct_count = bucket_correct.sum()
            observed_freq = correct_count / total if total > 0 else 0
            expected_freq = bucket_conf.mean()

            # Delete old calibration records for this bucket
            db.query(CalibrationMetrics).filter(
                CalibrationMetrics.market_type == market_type,
                CalibrationMetrics.confidence_bucket_min == min_conf,
                CalibrationMetrics.confidence_bucket_max == max_conf,
            ).delete()

            calibration_records.append(
                CalibrationMetrics(
                    market_type=market_type,
                    confidence_bucket_min=min_conf,
                    confidence_bucket_max=max_conf,
                    total_predictions=total,
                    correct_predictions=correct_count,
                    observed_frequency=observed_freq,
                    expected_frequency=expected_freq,
                )
            )

        db.add_all(calibration_records)
        db.commit()
        logger.info(f"Computed calibration metrics for {market_type}: {len(calibration_records)} buckets")
        return calibration_records

    def compute_rolling_accuracy(
        self, db: Session, market_type: str, window_days: int = 30
    ) -> RollingAccuracy:
        """
        Compute rolling accuracy for a market over a time window.

        Args:
            db: Database session
            market_type: Market type to compute accuracy for
            window_days: Time window in days

        Returns:
            RollingAccuracy record
        """
        since = datetime.now(timezone.utc) - timedelta(days=window_days)

        records = (
            db.query(PredictionAccuracy)
            .filter(
                PredictionAccuracy.market_type == market_type,
                PredictionAccuracy.match_date >= since,
            )
            .all()
        )

        if not records:
            logger.warning(f"No records found for rolling accuracy: {market_type} ({window_days} days)")
            return None

        total = len(records)
        correct = sum(1 for r in records if r.is_correct)
        accuracy = correct / total if total > 0 else 0

        confidences = [r.confidence for r in records if r.confidence is not None]
        avg_confidence = np.mean(confidences) if confidences else None

        # Compute average log loss
        log_losses = []
        for r in records:
            if r.predicted_probability is not None:
                y_true = 1 if r.is_correct else 0
                y_pred = r.predicted_probability
                # Clip to avoid log(0)
                y_pred = max(0.0001, min(0.9999, y_pred))
                ll = -(y_true * np.log(y_pred) + (1 - y_true) * np.log(1 - y_pred))
                log_losses.append(ll)
        avg_log_loss = np.mean(log_losses) if log_losses else None

        # Delete old rolling accuracy record
        db.query(RollingAccuracy).filter(
            RollingAccuracy.market_type == market_type,
            RollingAccuracy.window_days == window_days,
        ).delete()

        rolling = RollingAccuracy(
            market_type=market_type,
            window_days=window_days,
            total_predictions=total,
            correct_predictions=correct,
            accuracy=accuracy,
            avg_confidence=avg_confidence,
            avg_log_loss=avg_log_loss,
        )
        db.add(rolling)
        db.commit()
        logger.info(f"Computed rolling accuracy for {market_type} ({window_days} days): {accuracy:.4f}")
        return rolling

    def get_market_accuracy_summary(
        self, db: Session, market_type: str, window_days: int = 30
    ) -> Dict[str, Any]:
        """
        Get accuracy summary for a market.

        Args:
            db: Database session
            market_type: Market type
            window_days: Time window in days

        Returns:
            Dictionary with accuracy metrics
        """
        since = datetime.now(timezone.utc) - timedelta(days=window_days)

        records = (
            db.query(PredictionAccuracy)
            .filter(
                PredictionAccuracy.market_type == market_type,
                PredictionAccuracy.match_date >= since,
            )
            .all()
        )

        if not records:
            return {
                "market_type": market_type,
                "window_days": window_days,
                "total_predictions": 0,
                "accuracy": 0.0,
                "correct_predictions": 0,
            }

        total = len(records)
        correct = sum(1 for r in records if r.is_correct)
        accuracy = correct / total if total > 0 else 0

        return {
            "market_type": market_type,
            "window_days": window_days,
            "total_predictions": total,
            "correct_predictions": correct,
            "accuracy": accuracy,
        }


# Singleton instance
