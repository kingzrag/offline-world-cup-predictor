"""
Service for tracking predictions and computing accuracy metrics.

This service:
- Stores predictions when generated by the API
- Records immutable HistoricalPredictionRecord entries when matches finish
- Computes accuracy metrics across competitions, time windows, outcomes, and markets
"""

from datetime import datetime, timedelta, timezone
from typing import Dict, Any, List, Optional, Tuple
import numpy as np
from sqlalchemy.orm import Session
from sqlalchemy import func, and_, or_, extract

from models import (
    Match,
    Prediction,
    BettingMarketPrediction,
    PredictionAccuracy,
    CalibrationMetrics,
    RollingAccuracy,
)
from models.prediction_tracking import HistoricalPredictionRecord
from utils.logger import logger


class PredictionTrackingService:
    """Service for tracking predictions and computing analytics."""

    MARKET_TYPES = [
        "match_winner",  # 1X2
        "asian_handicap",
        "asian_total",
        "btts",
        "clean_sheet",
        "correct_score",
    ]

    def store_betting_market_prediction(
        self,
        db: Session,
        match_id: int,
        market_type: str,
        predicted_value: Optional[str],
        predicted_probability: Optional[float],
        model_version: str,
        source: str,
        prediction_data: Optional[Dict[str, Any]] = None,
    ) -> BettingMarketPrediction:
        prediction = BettingMarketPrediction(
            match_id=match_id,
            market_type=market_type,
            predicted_value=predicted_value,
            predicted_probability=predicted_probability,
            model_version=model_version,
            source=source,
            prediction_data=prediction_data,
        )
        db.add(prediction)
        db.commit()
        db.refresh(prediction)
        logger.info(f"Stored {market_type} prediction for match {match_id}")
        return prediction

    def evaluate_finished_matches(
        self, db: Session, since: Optional[datetime] = None
    ) -> int:
        """
        Evaluate predictions for recently finished matches and store permanent history.
        """
        if since is None:
            since = datetime.now(timezone.utc) - timedelta(days=365)

        matches = (
            db.query(Match)
            .filter(
                Match.status.in_(["FINISHED", "COMPLETED"]),
                Match.home_score.isnot(None),
                Match.away_score.isnot(None),
                Match.utc_date >= since,
            )
            .all()
        )

        evaluated_count = 0
        for match in matches:
            try:
                self._evaluate_match_predictions(db, match)
                evaluated_count += 1
            except Exception as e:
                logger.error(f"Failed to evaluate match {match.id}: {e}", exc_info=True)

        logger.info(f"Evaluated {evaluated_count} finished matches")
        return evaluated_count

    def _evaluate_match_predictions(self, db: Session, match: Match) -> None:
        """Evaluate all predictions for a single finished match and log history."""
        home_score = match.home_score if match.home_score is not None else 0
        away_score = match.away_score if match.away_score is not None else 0
        goal_diff = home_score - away_score
        total_goals = home_score + away_score

        actual_outcome = "HOME_WIN" if goal_diff > 0 else ("AWAY_WIN" if goal_diff < 0 else "DRAW")

        # 1. Update main Prediction table record
        main_pred = db.query(Prediction).filter_by(match_id=match.id).first()
        if main_pred:
            main_pred.actual_result = actual_outcome
            main_pred.is_correct = (main_pred.predicted_outcome == actual_outcome)
            main_pred.finished_at = match.utc_date
            main_pred.evaluated_at = datetime.now(timezone.utc)

        # 2. Immutable HistoricalPredictionRecord logging
        existing_hist = db.query(HistoricalPredictionRecord).filter_by(match_id=match.id).first()
        if not existing_hist and main_pred:
            confidence = max(
                main_pred.home_probability or 0.0,
                main_pred.draw_probability or 0.0,
                main_pred.away_probability or 0.0,
            )
            hist_record = HistoricalPredictionRecord(
                match_id=match.id,
                competition_code=match.competition.code if match.competition else "UNKNOWN",
                competition_name=match.competition.name if match.competition else "Unknown Competition",
                home_team=match.home_team.name if match.home_team else "Home Team",
                away_team=match.away_team.name if match.away_team else "Away Team",
                predicted_outcome=main_pred.predicted_outcome,
                home_probability=main_pred.home_probability,
                draw_probability=main_pred.draw_probability,
                away_probability=main_pred.away_probability,
                prediction_probability=confidence,
                expected_home_goals=main_pred.expected_home_goals,
                expected_away_goals=main_pred.expected_away_goals,
                actual_result=actual_outcome,
                actual_home_score=home_score,
                actual_away_score=away_score,
                is_correct=(main_pred.predicted_outcome == actual_outcome),
                match_date=match.utc_date,
            )
            db.add(hist_record)

        # 3. Update BettingMarketPrediction records
        predictions = (
            db.query(BettingMarketPrediction)
            .filter(BettingMarketPrediction.match_id == match.id)
            .all()
        )

        for pred in predictions:
            existing_acc = db.query(PredictionAccuracy).filter_by(
                match_id=match.id, market_type=pred.market_type
            ).first()
            if not existing_acc:
                accuracy = self._compute_prediction_accuracy(
                    pred, home_score, away_score, goal_diff, total_goals
                )
                if accuracy:
                    db.add(accuracy)

        db.commit()

    def _compute_prediction_accuracy(
        self,
        prediction: BettingMarketPrediction,
        home_score: int,
        away_score: int,
        goal_diff: int,
        total_goals: int,
    ) -> Optional[PredictionAccuracy]:
        market_type = prediction.market_type
        predicted_value = prediction.predicted_value
        predicted_prob = prediction.predicted_probability

        actual_value = None
        is_correct = False
        confidence = predicted_prob

        if market_type == "match_winner":
            actual_value = "HOME_WIN" if goal_diff > 0 else ("AWAY_WIN" if goal_diff < 0 else "DRAW")
            is_correct = predicted_value == actual_value
            confidence = prediction.prediction_data.get("confidence") if prediction.prediction_data else None

        elif market_type == "asian_handicap":
            actual_value = "1" if goal_diff > 0 else "0"
            predicted_val = "1" if predicted_value and predicted_value.startswith("Home") else "0"
            is_correct = predicted_val == actual_value
            confidence = prediction.predicted_probability

        elif market_type == "asian_total":
            actual_value = "1" if total_goals > 2.5 else "0"
            predicted_val = "1" if predicted_value and predicted_value.startswith("Over") else "0"
            is_correct = predicted_val == actual_value
            confidence = prediction.predicted_probability

        elif market_type == "btts":
            actual_value = "1" if (home_score > 0 and away_score > 0) else "0"
            predicted_val = "1" if predicted_value and predicted_value == "Yes" else "0"
            is_correct = predicted_val == actual_value
            confidence = prediction.predicted_probability

        elif market_type == "clean_sheet":
            actual_value = "1" if away_score == 0 else "0"
            predicted_val = "1" if predicted_value and predicted_value == "Yes" else "0"
            is_correct = predicted_val == actual_value
            confidence = prediction.predicted_probability

        elif market_type == "correct_score":
            actual_value = f"{home_score}-{away_score}"
            is_correct = predicted_value == actual_value
            confidence = prediction.prediction_data.get("probability") if prediction.prediction_data else None

        else:
            logger.warning(f"Unknown market type: {market_type}")
            return None

        return PredictionAccuracy(
            match_id=prediction.match_id,
            market_type=market_type,
            predicted_value=predicted_value,
            actual_value=actual_value,
            predicted_probability=predicted_prob,
            is_correct=is_correct,
            confidence=confidence,
            model_version=prediction.model_version,
            source=prediction.source,
            match_date=prediction.match.utc_date if prediction.match else datetime.now(timezone.utc),
        )

    # ── ANALYTICS QUERY METHODS ────────────────────────────────────────────────

    def get_overall_accuracy_analytics(self, db: Session) -> Dict[str, Any]:
        """Returns overall accuracy, total count, correct count, incorrect count."""
        total = db.query(HistoricalPredictionRecord).count()
        correct = db.query(HistoricalPredictionRecord).filter(HistoricalPredictionRecord.is_correct == True).count()
        incorrect = total - correct
        accuracy_rate = (correct / total * 100.0) if total > 0 else 0.0

        return {
            "total_predictions": total,
            "correct_predictions": correct,
            "incorrect_predictions": incorrect,
            "overall_accuracy_percent": round(accuracy_rate, 2),
        }

    def get_league_accuracy_analytics(self, db: Session) -> List[Dict[str, Any]]:
        """Returns accuracy metrics grouped by competition."""
        records = db.query(HistoricalPredictionRecord).all()
        by_comp: Dict[str, Dict[str, Any]] = {}

        for r in records:
            code = r.competition_code or "OTHER"
            name = r.competition_name or code
            if code not in by_comp:
                by_comp[code] = {
                    "competition_code": code,
                    "competition_name": name,
                    "total": 0,
                    "correct": 0,
                    "incorrect": 0,
                }
            by_comp[code]["total"] += 1
            if r.is_correct:
                by_comp[code]["correct"] += 1
            else:
                by_comp[code]["incorrect"] += 1

        results = []
        for code, data in sorted(by_comp.items(), key=lambda x: x[1]["total"], reverse=True):
            tot = data["total"]
            corr = data["correct"]
            rate = (corr / tot * 100.0) if tot > 0 else 0.0
            results.append({
                "competition_code": code,
                "competition_name": data["competition_name"],
                "total_predictions": tot,
                "correct_predictions": corr,
                "incorrect_predictions": data["incorrect"],
                "accuracy_percent": round(rate, 2),
            })
        return results

    def get_monthly_accuracy_analytics(self, db: Session) -> List[Dict[str, Any]]:
        """Returns accuracy metrics grouped by month (YYYY-MM)."""
        records = db.query(HistoricalPredictionRecord).order_by(HistoricalPredictionRecord.match_date.asc()).all()
        by_month: Dict[str, Dict[str, int]] = {}

        for r in records:
            if not r.match_date:
                continue
            month_key = r.match_date.strftime("%Y-%m")
            if month_key not in by_month:
                by_month[month_key] = {"total": 0, "correct": 0, "incorrect": 0}
            by_month[month_key]["total"] += 1
            if r.is_correct:
                by_month[month_key]["correct"] += 1
            else:
                by_month[month_key]["incorrect"] += 1

        results = []
        for month_key in sorted(by_month.keys()):
            data = by_month[month_key]
            tot = data["total"]
            corr = data["correct"]
            rate = (corr / tot * 100.0) if tot > 0 else 0.0
            results.append({
                "month": month_key,
                "total_predictions": tot,
                "correct_predictions": corr,
                "incorrect_predictions": data["incorrect"],
                "accuracy_percent": round(rate, 2),
            })
        return results

    def get_outcome_accuracy_analytics(self, db: Session) -> Dict[str, Any]:
        """Returns outcome breakdown accuracy (Home Win, Draw, Away Win)."""
        outcomes = ["HOME_WIN", "DRAW", "AWAY_WIN"]
        res = {}

        for outcome in outcomes:
            preds = db.query(HistoricalPredictionRecord).filter(
                HistoricalPredictionRecord.predicted_outcome == outcome
            ).all()
            total = len(preds)
            correct = sum(1 for p in preds if p.is_correct)
            rate = (correct / total * 100.0) if total > 0 else 0.0

            res[outcome.lower()] = {
                "predicted_outcome": outcome,
                "total_predictions": total,
                "correct_predictions": correct,
                "incorrect_predictions": total - correct,
                "accuracy_percent": round(rate, 2),
            }

        return res

    def get_market_accuracy_summary(
        self, db: Session, market_type: str, window_days: int = 365
    ) -> Dict[str, Any]:
        """Get accuracy summary for a market."""
        since = datetime.now(timezone.utc) - timedelta(days=window_days)

        records = (
            db.query(PredictionAccuracy)
            .filter(
                PredictionAccuracy.market_type == market_type,
                PredictionAccuracy.match_date >= since,
            )
            .all()
        )

        if not records:
            return {
                "market_type": market_type,
                "window_days": window_days,
                "total_predictions": 0,
                "accuracy": 0.0,
                "correct_predictions": 0,
            }

        total = len(records)
        correct = sum(1 for r in records if r.is_correct)
        accuracy = correct / total if total > 0 else 0

        return {
            "market_type": market_type,
            "window_days": window_days,
            "total_predictions": total,
            "correct_predictions": correct,
            "accuracy": accuracy,
        }

    def get_market_accuracy_analytics(self, db: Session) -> Dict[str, Any]:
        """Returns accuracy metrics for BTTS and Over/Under 2.5 markets."""
        btts_summary = self.get_market_accuracy_summary(db, "btts", window_days=365)
        ou_summary = self.get_market_accuracy_summary(db, "asian_total", window_days=365)

        return {
            "btts": {
                "market_type": "btts",
                "total_predictions": btts_summary["total_predictions"],
                "correct_predictions": btts_summary["correct_predictions"],
                "accuracy_percent": round(btts_summary["accuracy"] * 100.0, 2),
            },
            "over_under_2_5": {
                "market_type": "asian_total",
                "total_predictions": ou_summary["total_predictions"],
                "correct_predictions": ou_summary["correct_predictions"],
                "accuracy_percent": round(ou_summary["accuracy"] * 100.0, 2),
            }
        }

    def get_recent_historical_predictions(
        self, db: Session, limit: int = 50, offset: int = 0
    ) -> List[Dict[str, Any]]:
        """Returns paginated list of recent historical predictions."""
        records = (
            db.query(HistoricalPredictionRecord)
            .order_by(HistoricalPredictionRecord.match_date.desc())
            .offset(offset)
            .limit(limit)
            .all()
        )

        return [
            {
                "id": r.id,
                "match_id": r.match_id,
                "competition_code": r.competition_code,
                "competition_name": r.competition_name,
                "home_team": r.home_team,
                "away_team": r.away_team,
                "predicted_outcome": r.predicted_outcome,
                "home_probability": r.home_probability,
                "draw_probability": r.draw_probability,
                "away_probability": r.away_probability,
                "prediction_probability": r.prediction_probability,
                "expected_home_goals": r.expected_home_goals,
                "expected_away_goals": r.expected_away_goals,
                "actual_result": r.actual_result,
                "actual_home_score": r.actual_home_score,
                "actual_away_score": r.actual_away_score,
                "is_correct": r.is_correct,
                "match_date": r.match_date.isoformat() if r.match_date else None,
                "recorded_at": r.recorded_at.isoformat() if r.recorded_at else None,
            }
            for r in records
        ]


